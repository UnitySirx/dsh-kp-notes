/* rk-study · client/sizes.js —— 全插件的「宽高」都在这一个文件里
 *
 * 为什么要单独一个文件：这些数字原先散在三处 —— 画布几何写死在 client/canvas.js、
 * 卡片默认宽度写死在 client/cards.js、弹窗/抽屉/编辑器高度全埋在 client/css.js 的样式串里。
 * 想试「卡片宽一点 / 编辑窗大一点 / 舞台留白多一点」得同时改三四个文件，还容易只改一处
 * （比如右键菜单宽度在 canvas.js 与 css.js 各写了一遍 196）。现在只改这里，三边一起变。
 *
 * 怎么生效：保存后按 ⌘R 刷新页面即可（只动 client/ 下的文件，宿主半没变）。
 *   如果刷新后毫无变化，把插件在侧栏关一次再开一次（入口 bundle 带 rev 哈希，见 README「五、插件实现」）。
 *
 * 单位约定：**纯数字 = px**（写样式时自己补单位：`${px(S.canvas.cardWidth)}` 或 `${S.canvas.cardWidth}px`）；
 *   需要 vh / % 的（弹窗高度上限这类）直接写成带单位的字符串。
 *
 * 卡片那部分是**按级分开的两套**，互不影响：`rootCanvas` = 根画布（还没进任何画布）上的学习画布卡片，
 *   `canvas` = 进了某张画布之后的章节卡片；缩放上下限是两级共用的 `stage`。
 *
 * 不在这个文件里的：装饰性细线（1-3px 高亮条）、圆点/图标/单选框这类 1-18px 的微件、
 *   以及 100% / auto 这种跟着父容器走的自适应值 —— 它们改起来不会「看起来大一点/小一点」，不搬。
 */

export function createSizes() {
	const SIZES = {
		/* ===== 一、根画布（还没进任何画布）：学习画布卡片 + 舞台 =====
		 * 卡片位置 = 列号 * (cardWidth + cardGap)，行号 * (cardHeight + cardGap)；
		 * 「复位铺满」用 stageBox（舞台可视宽度，含内边距）算出能放几列，再按这套尺寸反推缩放。 */
		rootCanvas: {
			cardWidth: 450, /* 学习画布卡片宽度（只影响根画布这一级）。改宽 → 每行能放的列数自动变少（见 rootColsMax） */
			cardHeight: 188, /* 学习画布卡片高度。卡片里的标题/进度/统计是固定行高，加太高会留白 */
			cardGap: 18, /* 卡片间距，横向纵向共用 */
			rootColsMax: 3, /* 最多排几列：屏幕再宽也不超过这个数 */
			stagePadX: 22, /* 舞台左右内边距（左右各一份，算列数与铺满时减掉 2 份）。要与 css.js 的 .rk-stage 左右 padding 一致 */
			stagePadTop: 20, /* 舞台顶部内边距 */
			stagePadBottom: 60, /* 舞台底部内边距：给浮动按钮/提示留位置 */
		},

		/* ===== 二、画布内（已经进了某张画布）：章节卡片 + 舞台 =====
		 * 章节卡排成一行（x = 序号 * (cardWidth + cardGap)），宽用这里的 cardWidth；
		 * 卡高由内容决定（css.js 的 .rk-chapter），所以这里没有 cardHeight。 */
		canvas: {
			cardWidth: 372, /* 章节卡片宽度（只影响画布内这一级） */
			cardGap: 18, /* 章节卡片之间的间距 */
			stagePadX: 22, /* 舞台左右内边距（与根画布那份互相独立） */
			stagePadTop: 20, /* 舞台顶部内边距 */
			stagePadBottom: 60, /* 舞台底部内边距 */
		},

		/* ===== 三、舞台缩放范围（两级共用） =====
		 * 它管的是「这个舞台能缩放到多少」，与卡片多大无关，所以不按级分。 */
		stage: {
			minScale: 0.2, /* 缩小下限（一行卡片很长时，复位允许缩到这个比例） */
			maxScale: 2.4, /* 放大上限 */
		},

		/* ===== 四、思维导图（左→右的层级树） =====
		 * 下面四个数组的**下标 = 层深**：0 根 → 1 章节 → 2 小节 → 3 知识点 → 4 知识点正文。
		 * 布局算法只读这些数，真实节点高度由 DOM 量出来再回填（正文那层默认 220 只是量之前的估值）。 */
		mindmap: {
			colX: [0, 258, 556, 828, 1180], /* 每层节点左边缘的 x，改大 = 列与列之间更空 */
			colW: [214, 268, 250, 300, 470], /* 每层节点宽度：正文那层放整篇 markdown，要给足 */
			rowH: [40, 34, 30, 30, 220], /* 每层节点默认高度（正文层会被实测高度覆盖） */
			rowGap: [18, 13, 10, 10, 12], /* 同层相邻节点的纵向间距 */
			groupGap: 12, /* 不同父节点的子树之间额外多留的间距，让层次分开 */
			canvasPadX: 24, /* 导图内容尺寸（画布可滚动范围）额外加的横向留白 */
			canvasPadY: 8, /* 同上，纵向 */
		},

		/* ===== 五、右键菜单 / 浮层 =====
		 * 菜单位置由 canvas.js 按菜单尺寸摆（贴边时自动翻向另一侧），尺寸本身写在样式里。 */
		menu: {
			width: 196, /* 右键菜单最小宽度 */
			itemH: 30, /* 每项高度 */
			sepH: 11, /* 分隔线占位高度（含上下外边距） */
			pad: 10, /* 菜单内边距，定位时要减掉 */
			markdownW: 252, /* markdown 工具栏「插入模板」下拉宽度 */
			markdownMaxH: 340, /* 该下拉的最大高度，超了内部滚动 */
			skinW: 268, /* 皮肤（配色）选择浮层宽度 */
		},

		/* ===== 六、弹窗 / 抽屉 / 详情面板 =====
		 * 这里每个宽度实际都写成 `min(<数字>px, <百分比>%)`：面板窗口很小时按百分比收窄。 */
		dialog: {
			modalW: 430, /* 默认小弹窗（改名/新建/确认）宽度 */
			modalNarrowPct: 96, /* 面板很窄时（容器宽度 < breakpoints.narrow）小弹窗改用的百分比宽度 */
			pcardW: 1180, /* 知识点/问题编辑大弹窗宽度 */
			pcardH: 840, /* 大弹窗高度上限（再配 86vh / 92% 两道保险） */
			guideW: 880, /* 作图/学习指南弹窗宽度 */
			guideMaxH: '88vh', /* 指南弹窗高度上限 */
			binW: 620, /* 回收站弹窗宽度 */
			binMaxH: '76vh', /* 回收站弹窗高度上限 */
			binListMaxH: '44vh', /* 回收站里文件列表的高度上限 */
			settingsW: 560, /* 设置（根目录/皮肤/字号那一栏）宽度 */
			drawerW: 620, /* 右侧抽屉（查看/编辑）宽度 */
			drawerWideW: 1120, /* 双栏抽屉（源码 + 预览）宽度 */
			detailW: 760, /* 学习画布右侧详情面板宽度上限 */
			detailPct: 52, /* 详情面板占面板宽度的百分比上限 */
			detailMinW: 340, /* 详情面板最小宽度：再窄正文就挤了 */
			docMaxW: 920, /* 正文最大阅读宽度（大屏上不让一行太长） */
			docMaxWideW: 980, /* 面板够宽时正文的最大阅读宽度 */
		},

		/* ===== 七、编辑器与预览 =====
		 * min 高度决定「打开时有多高」，max 高度决定「什么时候出现内部滚动条」。 */
		editor: {
			textareaMinH: 220, /* 新建/编辑抽屉里的源码 textarea 最小高度 */
			mdeditMinH: 220, /* markdown 编辑区（Milkdown 容器）的最小高度 */
			growTextareaMinH: 150, /* 被拉伸的「源码」栏最小高度（编辑弹窗与窄面板两处共用） */
			splitTextareaMinH: 120, /* 双栏模式（源码 + 预览并排）下源码栏的最小高度 */
			mdEditorMinH: 110, /* 可视化编辑器（Milkdown）最小高度，也是它加载中的占位高度 */
			mdEditorMaxH: 300, /* 可视化编辑器最大高度，超出内部滚动 */
			previewInlineMaxH: 300, /* 编辑器下方内联预览的高度上限 */
			previewInlineBodyH: 262, /* 上面那块的正文区高度（留出标题条） */
		},

		/* ===== 八、零散 ===== */
		misc: {
			gitFilesMaxH: '30vh', /* git 面板改动文件列表高度上限 */
			gitMsgMinH: 74, /* commit message 输入框最小高度 */
			gitOutMaxH: 118, /* git 命令输出区高度上限 */
			pointBodyMaxH: 96, /* 一级画布卡片里「正文摘要」的最大高度，超出截断 */
		},

		/* ===== 九、容器宽度断点 =====
		 * css.js 用 @container rk (max-width: <数字>px) 切换紧凑布局：
		 * 面板宽度小于 wide → 详情面板与正文让位；小于 narrow → 弹窗铺满、抽屉全宽；小于 tiny → 标题栏收起。
		 * 如果把上面的弹窗/卡片调大了，这里通常要跟着涨。 */
		breakpoints: {
			wide: 1180,
			medium: 1000,
			narrow: 860,
			tiny: 700,
		},
	};

	/* 拼样式时用：px(S.canvas.cardGap) === '18px' */
	const px = (value) => value + 'px';

	return { SIZES, px };
}
